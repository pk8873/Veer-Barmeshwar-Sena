class Command(BaseCommand):
    help = "Create five sourced Hindi history posts about Brahmeshwar Mukhiya (idempotent)."

    def handle(self, *args, **options):
        User = get_user_model()
        author = User.objects.filter(is_superuser=True).order_by("pk").first()
        if author is None:
            author = User.objects.filter(is_staff=True).order_by("pk").first()
        if author is None:
            self.stdout.write(self.style.WARNING("No staff/admin user exists yet; skipping historical post seeding."))
            return

        created_count = 0
        updated_count = 0
        now = timezone.now()
        for index, item in enumerate(POSTS):
            defaults = {
                "author": author,
                "title": item["title"],
                "body": item["body"].strip(),
                "status": Post.Status.PUBLISHED,
                "published_at": now - timezone.timedelta(minutes=(len(POSTS) - index)),
                "is_pinned": item.get("pinned", False),
            }
            _, created = Post.objects.update_or_create(slug=item["slug"], defaults=defaults)
            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(self.style.SUCCESS(
            f"Historical posts ready: {created_count} created, {updated_count} updated."
        ))
